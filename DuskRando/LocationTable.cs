using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Newtonsoft.Json.Linq;
using UnityEngine;

namespace DuskRando
{
    public class LocationEntry
    {
        public long Id;
        public string Name;
        public string Level;      // "E1M6"
        public string Scene;      // "E1M5AndAHalf"
        public string Category;   // "weapons", "keys", ...
        public string Object;     // GameObject name in the scene
        public Vector3 Position;  // authored world position
        public bool HasPosition;
    }

    public class LevelEntry
    {
        public string Code;
        public string Scene;
        public string Name;
        public int Episode;
        public bool Secret;
        public List<string> Keys = new List<string>();
    }

    /// <summary>Location data generated by tools/gen_data.py (embedded from apworld/dusk/data/locations.json).</summary>
    public static class LocationTable
    {
        public static readonly List<LevelEntry> Levels = new List<LevelEntry>();
        public static readonly Dictionary<long, LocationEntry> ById = new Dictionary<long, LocationEntry>();
        static readonly Dictionary<string, List<LocationEntry>> byScene = new Dictionary<string, List<LocationEntry>>();
        public static readonly Dictionary<string, LevelEntry> LevelByScene = new Dictionary<string, LevelEntry>();
        public static readonly Dictionary<string, LevelEntry> LevelByCode = new Dictionary<string, LevelEntry>();

        public static void Load()
        {
            string json;
            using (var s = typeof(LocationTable).Assembly.GetManifestResourceStream("DuskRando.locations.json"))
            using (var r = new StreamReader(s))
                json = r.ReadToEnd();
            var root = JObject.Parse(json);
            foreach (var l in root["levels"])
            {
                var lvl = new LevelEntry
                {
                    Code = (string)l["code"], Scene = (string)l["scene"], Name = (string)l["name"],
                    Episode = (int)l["episode"], Secret = (bool)l["secret"],
                    Keys = l["keys"].Select(k => (string)k).ToList(),
                };
                Levels.Add(lvl);
                LevelByScene[lvl.Scene] = lvl;
                LevelByCode[lvl.Code] = lvl;
            }
            foreach (var l in root["locations"])
            {
                var e = new LocationEntry
                {
                    Id = (long)l["id"], Name = (string)l["name"], Level = (string)l["level"],
                    Scene = (string)l["scene"], Category = (string)l["category"], Object = (string)l["object"],
                };
                var pos = l["pos"] as JArray;
                if (pos != null)
                {
                    e.Position = new Vector3((float)pos[0], (float)pos[1], (float)pos[2]);
                    e.HasPosition = true;
                }
                ById[e.Id] = e;
                if (!byScene.TryGetValue(e.Scene, out var list)) byScene[e.Scene] = list = new List<LocationEntry>();
                list.Add(e);
            }
            Plugin.Log.LogInfo($"Loaded {ById.Count} DUSK locations in {Levels.Count} levels");
        }

        public static IEnumerable<LocationEntry> InScene(string scene) =>
            byScene.TryGetValue(scene, out var l) ? l : Enumerable.Empty<LocationEntry>();

        public static LocationEntry LevelComplete(string scene) =>
            InScene(scene).FirstOrDefault(l => l.Category == "level_complete");

        /// <summary>
        /// Find the location for a scene object by name + authored position. Positions are matched with a
        /// tolerance because pickups settle a little (PickupGravity) and the table rounds to 2 decimals.
        /// </summary>
        public static LocationEntry Match(string scene, GameObject go, float tolerance = 0.75f)
        {
            LocationEntry best = null;
            float bestDist = tolerance;
            var p = go.transform.position;
            foreach (var e in InScene(scene))
            {
                if (!e.HasPosition || e.Object != go.name) continue;
                float d = Vector3.Distance(e.Position, p);
                if (d < bestDist) { best = e; bestDist = d; }
            }
            return best;
        }
    }
}
